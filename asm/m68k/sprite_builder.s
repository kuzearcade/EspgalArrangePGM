; Sprite list builder for the enhanced sprite engine (espgalarr).
;
; Replaces the frame-end builder, which merged every sprite layer into one work list,
; capped it at 251 sprites (plus a dummy every 50) and copied it to the 256-entry IGS023
; list at 0x800000. This version is table driven and has no 256 limit:
;   * layers are emitted in the original priority order straight from their own lists
;     (12-byte work entries -> 10-byte hardware entries, same field transform and global
;     scroll offset as the original);
;   * the first 256 hardware entries fill the main list at 0x800000 (no terminator when
;     full, exactly what the IGS023 DMA reads);
;   * further entries go to the continuation list in cart ARM RAM at 0xD0C840, read by the
;     enhanced sprite engine (MAME `espgalarr` machine config); stock hardware shows the
;     first 256 as before;
;   * the dummy entry cadence (after 51 sprites, then every 50) is kept across both lists.
; The layer table (base, byte-counter address, capacity in entries) is generated by the build
; from the layout stage (espgalarr/stages/layout.py: sprite_layout) at the `@layer_table` line.
; A counter above the capacity (e.g. uninitialised RAM on the first frame) is clamped, and every
; counter is cleared once its layer has been emitted.
; The entries are copied in runs: a run ends at the layer's end, at the next dummy entry or at
; the end of the current list, so the per-entry loop has no slot or cadence checks (the output
; is the same as one check per entry; about 70 cycles less per sprite, the builder being the
; largest added load in heavy scenes: tools/prof68k.py). With no global scroll offset (all but
; screen shakes) the position long is copied as is (entry_fast).
;
; replaces 0x113D7A
; entry sprite_builder

        .equ    MAIN_LIST, $800000
        .equ    MAIN_SLOTS, 256
        .equ    EXT_LIST, $d0c840
        .equ    EXT_SLOTS, 1400         ; continuation entries before its terminator (ends 0xD0FFFA)
        .equ    SCROLL_OFS, $807058

sprite_builder:
        jsr     orig_112ad8             ; sprite DMA off while the list is rewritten
        movem.l d5/a4,-(a7)
        move.l  SCROLL_OFS.l,d2
        lea     MAIN_LIST.l,a0
        move.w  #MAIN_SLOTS,d6          ; free slots in the current list
        suba.l  a4,a4                   ; 0 = main list, 1 = continuation
        moveq   #$33,d4                 ; real entries before the next dummy entry
        move.l  #$07ff3fff,d7           ; position field mask
        lea     layer_table(pc),a3
next_layer:
        move.l  (a3)+,d0
        beq.w   finish
        movea.l d0,a1
        movea.l (a3)+,a2
        move.w  (a3)+,d0                ; capacity in entries
        moveq   #0,d3
        move.w  (a2),d3                 ; layer size in bytes (12 per entry)
        clr.w   (a2)
        divu    #12,d3
        cmp.w   d0,d3
        bls.w   count_ok
        move.w  d0,d3
count_ok:
        tst.w   d3                      ; d3: entries left in the layer
        beq.w   next_layer
next_run:
        tst.w   d4
        bne.w   no_dummy
        moveq   #$32,d4
        tst.w   d6
        bne.w   dummy_slot
        bsr.w   switch_list
dummy_slot:
        subq.w  #1,d6
        move.l  #$fc003800,(a0)+        ; off-screen dummy entry
        clr.l   (a0)+
        move.w  #$201,(a0)+
no_dummy:
        tst.w   d6
        bne.w   run_length
        bsr.w   switch_list
run_length:
        move.w  d3,d5                   ; run = min(layer left, before dummy, free slots)
        cmp.w   d4,d5
        bls.w   run_dummy_ok
        move.w  d4,d5
run_dummy_ok:
        cmp.w   d6,d5
        bls.w   run_slots_ok
        move.w  d6,d5
run_slots_ok:
        sub.w   d5,d3
        sub.w   d5,d4
        sub.w   d5,d6
        subq.w  #1,d5
        tst.l   d2
        beq.w   entry_fast
entry_loop:
        move.l  (a1)+,d0
        move.l  d0,d1
        andi.l  #$f800f800,d0
        and.l   d7,d1
        add.l   d2,d1
        and.l   d7,d1
        or.l    d0,d1
        move.l  d1,(a0)+
        move.l  (a1)+,(a0)+
        move.w  (a1)+,(a0)+
        move.b  (a1)+,d0
        or.b    (a1)+,d0
        move.b  d0,-6(a0)
        dbra    d5,entry_loop
        tst.w   d3
        bne.w   next_run
        bra.w   next_layer

; no global scroll offset (the usual case): the position long needs no fix-up, since
; (p & $f800f800) | ((p & $07ff3fff) + 0) & $07ff3fff = p; about 90 cycles a sprite, not 146
entry_fast:
        move.l  (a1)+,(a0)+
        move.l  (a1)+,(a0)+
        move.w  (a1)+,(a0)+
        move.b  (a1)+,d0
        or.b    (a1)+,d0
        move.b  d0,-6(a0)
        dbra    d5,entry_fast
        tst.w   d3
        bne.w   next_run
        bra.w   next_layer

; switch_list: the current list is full: go on in the continuation list, or end the build when
; that is full too.
switch_list:
        cmpa.w  #0,a4
        bne.w   lists_full
        movea.w #1,a4
        lea     EXT_LIST.l,a0
        move.w  #EXT_SLOTS,d6
        rts
lists_full:
        addq.l  #4,a7                   ; drop the return address
clear_rest:
        move.l  (a3)+,d0                ; layers not emitted: clear their counters
        beq.w   finish
        movea.l (a3)+,a2
        clr.w   (a2)
        addq.l  #2,a3
        bra.w   clear_rest
finish:
        move.l  a4,d7                   ; (the list flag, as before)
        tst.w   d7
        bne.w   terminate               ; in the continuation list: terminate it
        tst.w   d6
        beq.w   main_full
        bsr.w   write_terminator        ; main list ends early
main_full:
        lea     EXT_LIST.l,a0           ; continuation list is empty
terminate:
        bsr.w   write_terminator
        movem.l (a7)+,d5/a4
        jmp     orig_112aca             ; sprite DMA back on

write_terminator:
        clr.l   (a0)+
        clr.l   (a0)+
        clr.w   (a0)+
        rts

        .align  4
; (layer list base, byte counter, capacity) in emit order; first = highest priority.
layer_table:
; @layer_table
        dc.l    0
